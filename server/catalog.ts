export async function seedEconomicCatalog(): Promise<void> {
  for (const item of INDICATOR_CATALOG) {
    await query(
      `INSERT INTO economic_indicator_catalog
        (indicator_key, provider, display_name_ko, category, frequency, unit, currency, mapping_json, source_url, active, verified_at)
       VALUES ($1,$2,$3,$4,$5,$6,$7,$8,$9,1,$10)
       ON CONFLICT (indicator_key) DO UPDATE SET
         provider = EXCLUDED.provider,
         display_name_ko = EXCLUDED.display_name_ko,
         category = EXCLUDED.category,
         frequency = EXCLUDED.frequency,
         unit = EXCLUDED.unit,
         currency = EXCLUDED.currency,
         mapping_json = EXCLUDED.mapping_json,
         source_url = EXCLUDED.source_url,
         verified_at = EXCLUDED.verified_at,
         updated_at = CURRENT_TIMESTAMP`,
      [
        item.indicatorKey,
        item.provider,
        item.displayNameKo,
        item.category,
        item.frequency,
        item.unit,
        item.currency ?? null,
        JSON.stringify(item.mapping),
        item.sourceUrl,
        item.verifiedAt,
      ]
    );
  }
}

export function sourceLabel(provider: string): string {
  if (provider === 'ECOS') return 'Bank of Korea ECOS';
  if (provider === 'EIA') return 'U.S. EIA';
  if (provider === 'IMF') return 'IMF PCPS';
  return provider;
}
